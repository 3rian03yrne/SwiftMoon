"""Generate SwiftMoon's yearly Delta T table from Skyfield.

ADR 3 amendment: the Espenak-Meeus (2006) polynomials predict Delta T far too
high after ~2010 (about 107 s too high by 2100), so 1900-2101 uses a yearly
table sampled from Skyfield's built-in Delta T model instead. SwiftMoon
interpolates it linearly and uses Espenak-Meeus only outside the table.

Usage (from the repository root):
    python scripts/lunar-validation/generate_delta_t.py

Writes Sources/SwiftMoon/Meeus/DeltaTTable.swift. No ephemeris file is needed.
Values after the latest IERS data are predictions; regenerate with a newer
Skyfield to pick up newer measurements and predictions.
"""
import datetime
import os

import skyfield
from skyfield.api import load

FIRST_YEAR, LAST_YEAR = 1900, 2101
J2000 = 2451545.0
OUT = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "..", "..", "Sources", "SwiftMoon", "Meeus", "DeltaTTable.swift",
)

ts = load.timescale()
values = []
for year in range(FIRST_YEAR, LAST_YEAR + 1):
    # Same decimal-year scale as JulianDay.decimalYear in Swift:
    # y = 2000 + (JD - 2451545) / 365.25.
    jd = J2000 + (year - 2000) * 365.25
    values.append(float(ts.tt_jd(jd).delta_t))

rows = []
for i in range(0, len(values), 8):
    chunk = values[i:i + 8]
    rows.append("        " + ", ".join(f"{v:.3f}" for v in chunk) + ",")

swift = f"""//
//  DeltaTTable.swift
//  SwiftMoon
//
//  GENERATED by scripts/lunar-validation/generate_delta_t.py. Do not edit.
//
//  ΔT = TT − UT in seconds at the start of each decimal year
//  y = 2000 + (JD − 2451545) / 365.25, for {FIRST_YEAR}–{LAST_YEAR}.
//  Source: Skyfield {skyfield.__version__} built-in ΔT model (IERS measurements,
//  then its long-term prediction). Generated {datetime.date.today().isoformat()}.
//  Values after the latest IERS data are predictions.
//

enum DeltaTTable {{
    static let firstYear = {FIRST_YEAR}
    static let lastYear = {LAST_YEAR}

    static let seconds: [Double] = [
{chr(10).join(rows)}
    ]
}}
"""

with open(OUT, "w") as f:
    f.write(swift)
print(f"Wrote {len(values)} yearly Delta T values ({FIRST_YEAR}-{LAST_YEAR}) to {os.path.relpath(OUT)}")
print(f"  {FIRST_YEAR}: {values[0]:.2f} s   2025: {values[2025 - FIRST_YEAR]:.2f} s   "
      f"{LAST_YEAR}: {values[-1]:.2f} s")
